#!/bin/sh
# Compiles the GPU renderer's GLSL shaders to SPIR-V and embeds them in
# runtime/src/video/gpu/shaders.inc (committed, so building the game doesn't need glslc).
set -e
R=$(cd "$(dirname "$0")/.." && pwd)
S=$R/runtime/src/video/gpu/shaders
OUT=$R/runtime/src/video/gpu/shaders.inc
TMP=$(mktemp -d)
{
    echo "// Generated by tools/build-shaders.sh from runtime/src/video/gpu/shaders; do not edit."
    for f in pica.vert pica.frag fullscreen.vert blit_lcd.frag; do
        glslc -O --target-env=vulkan1.0 "$S/$f" -o "$TMP/$f.spv"
        name=$(echo "$f" | tr . _)
        echo "static const unsigned char SPIRV_${name}[] = {"
        od -An -v -tx1 "$TMP/$f.spv" | sed 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/    /'
        echo "};"
    done
    # pica.frag again, writing w-buffer depth (see the shader)
    glslc -O --target-env=vulkan1.0 -DWDEPTH "$S/pica.frag" -o "$TMP/pica_wdepth.frag.spv"
    echo "static const unsigned char SPIRV_pica_wdepth_frag[] = {"
    od -An -v -tx1 "$TMP/pica_wdepth.frag.spv" | sed 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/    /'
    echo "};"
} > "$OUT"
rm -rf "$TMP"
echo "wrote $OUT"
